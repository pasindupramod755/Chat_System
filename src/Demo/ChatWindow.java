    @Override
    public void sendMessage(String msg) {
        if (!msg.substring(0, getTitle().length()).equalsIgnoreCase(getTitle())) {
            jTextArea1.append(msg + "\n");
        } else {
            jTextArea1.append("Me" + msg.substring(getTitle().length()) + "\n");
        }
    }

